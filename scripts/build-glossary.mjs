#!/usr/bin/env node
/**
 * build-glossary.mjs
 *
 * Regenerates public/content/glossary.json — the "key term store" behind
 * src/components/GlossaryTerm.tsx's inline tooltip. Same shape of pipeline
 * as taxonomy.json (curated source -> generated JSON) and relationships.json
 * (computed cross-content data): scripts/lib/glossary-source.mjs holds the
 * hand-curated term -> definition dictionary; this script enriches it with
 * computed `usageCount`/`usedIn` by scanning every skillup exam's domain
 * notes and every skill track's lesson notes for backtick-wrapped mentions
 * of each term, so a viewer can see which other lessons/domains also use a
 * term (the "relation" half) alongside how often (the "numbers" half) —
 * without needing a live IntelliSense-style analyzer.
 *
 * All curated terms are always emitted, even ones with zero current
 * mentions (usageCount: 0, usedIn: []) — the tooltip must keep working the
 * moment a future note starts using an existing term, not just be a record
 * of past scans. This mirrors taxonomy.json's tier-2 nodes, which persist
 * across runs even when no vertical currently tags them.
 *
 * Called from build-content-intelligence.mjs's main() so it regenerates on
 * the same cadence as stats.json/relationships.json (every promotion and
 * every near-real-time vertical push) — never invoked standalone in CI, but
 * runnable directly for local iteration: `node scripts/build-glossary.mjs`.
 *
 * Usage: node scripts/build-glossary.mjs
 */
import { writeFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import { loadSkillupCatalog, loadSkillupNoteFile } from './lib/content-sources.mjs';
import { GLOSSARY_SOURCE } from './lib/glossary-source.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// One entry per notes file across every exam/skill-track, however each
// vertical's schema happens to nest it — classic exams have domains[],
// skill tracks have modules[].lessons[]. Two different `url` shapes on
// purpose: a domain deep-links straight to its notes route, but a skill-
// track lesson's notes render inline on the track overview (see
// SkillTrackHome.tsx) — there is no per-lesson notes route to link to.
function collectNoteDocs(catalog) {
  const docs = [];
  for (const exam of catalog?.exams ?? []) {
    if (exam.kind === 'skill-track') {
      for (const mod of exam.modules ?? []) {
        for (const lesson of mod.lessons ?? []) {
          if (!lesson.notesFile) continue;
          docs.push({
            notesFile: lesson.notesFile,
            id: `exam/${exam.id}`,
            title: `${exam.title} — ${lesson.title}`,
            url: `/skillup/${exam.id}`,
          });
        }
      }
    } else {
      for (const domain of exam.domains ?? []) {
        if (!domain.notesFile) continue;
        docs.push({
          notesFile: domain.notesFile,
          id: `exam/${exam.id}/domain-${domain.id}`,
          title: `${exam.title} — ${domain.title}`,
          url: `/skillup/${exam.id}/notes?d=${domain.id}`,
        });
      }
    }
  }
  return docs;
}

/**
 * Returns the full terms[] array for glossary.json. Exported so
 * build-content-intelligence.mjs can call this inline (one process, one
 * run) instead of shelling out to a second script.
 */
export async function buildGlossaryTerms(catalog) {
  const entries = Object.entries(GLOSSARY_SOURCE).map(([term, definition]) => ({
    id: term.toLowerCase(),
    term,
    definition,
    usageCount: 0,
    usedIn: [], // { id, title, url }, deduped by id
  }));
  const noteDocs = collectNoteDocs(catalog);
  for (const doc of noteDocs) {
    let text;
    try {
      text = await loadSkillupNoteFile(doc.notesFile);
    } catch (err) {
      console.error(`⚠ glossary: could not fetch ${doc.notesFile}: ${err.message}`);
      continue;
    }
    if (!text) continue;

    for (const entry of entries) {
      const re = new RegExp('`' + escapeRegExp(entry.term) + '`', 'g');
      const matches = text.match(re);
      if (!matches) continue;
      entry.usageCount += matches.length;
      if (!entry.usedIn.some((u) => u.id === doc.id)) {
        entry.usedIn.push({ id: doc.id, title: doc.title, url: doc.url });
      }
    }
  }

  return entries;
}

async function main() {
  const catalog = await loadSkillupCatalog().catch((e) => {
    console.error(`⚠ glossary: skillup catalog unavailable: ${e.message}`);
    return null;
  });
  const terms = await buildGlossaryTerms(catalog);

  const glossary = {
    schemaVersion: 1,
    generated: new Date().toISOString(),
    note: 'Auto-generated by scripts/build-glossary.mjs from scripts/lib/glossary-source.mjs — definitions are hand-curated there; usageCount/usedIn are computed by scanning skillup exam/skill-track notes for backtick-wrapped mentions. Regenerates alongside relationships.json/stats.json in build-content-intelligence.mjs. Do not hand-edit this file.',
    terms,
  };

  const outDir = join(root, 'public', 'content');
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'glossary.json'), JSON.stringify(glossary, null, 2) + '\n', 'utf-8');

  const used = terms.filter((t) => t.usageCount > 0).length;
  console.log(`Glossary written: ${terms.length} term(s), ${used} in active use across content`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
